// payoff-reference.mjs — SPIKE S-B's STREET-SIMULATION GROUND TRUTH, transcribed so the fit that
// reads it is reproducible from this repository forever. DATA ONLY: no logic, no opinion, nothing
// derived. `payoff-fit.mjs` is what reads it; `payoff-model.mjs` carries the fit's frozen output.
//
// WHY THIS FILE EXISTS AT ALL. V3-PLAN §6's row for the payoff estimator reads "fitted to S-B's
// street-sim ground truth; residuals shipped like `benchmarks.disputed`". A fit is only an ANCHOR
// if the thing it was fitted to can be produced again — otherwise the coefficients are numbers
// somebody typed, which is the one thing §6 forbids. S-B's raw output lived in its own spike
// worktree (`scripts/spike/sb-results.json`, 165 KB, branch `worktree-wf_5a8a2571-726-3`), which is
// disposable by design. So the 300 evaluation points are transcribed here, unrounded, exactly as
// the spike wrote them, and `test/payoff-model.test.mjs` re-derives every frozen coefficient in
// `payoff-model.mjs` from THIS array. Nothing about the estimator is typed.
//
// WHAT ONE ROW IS. S-B ran REF3 — heads-up, pot normalised to 1, effective stack = spr, three
// streets, both players estimating equity against the opponent's CELL (the payoff signature makes
// ranges public) over 32 sampled runouts x 24 range hands per street, acting on a polar threshold
// policy — for 50 stratified cell pairs x spr {1, 4, 10} x {IP, OOP} = 300 points, 20,000 shared
// deals per pair, on tree `e6c6641`. A row is one (pair, spr, position):
//
//   [ a, b, spr, ip, ref, se, potMult, invShare, eqAB, test ]
//
//   a, b       indices into CELLS below — hero first, exactly the order `payoff()` takes
//   spr        1 | 4 | 10, the three simulated stack depths
//   ip         1 = hero has position, 0 = hero is out of position
//   ref        REF3's `ev`, the RATIO OF EXPECTATIONS E[W]/E[F] (S-B's own definition: the only
//              reading of §2's "expected final-pot share" that makes I33(b) exact per hand)
//   se         one standard error on `ref`, from the 20,000 deals that actually ran
//   potMult    E[final pot] / potSize, uncalled bets included. S-B's measured range 1.603 .. 11.865
//   invShare   S-B's OWN reading: E[hero invested TOTAL] / E[F]. **NOT** the interface's key of the
//              same name. V3-PLAN §2's `Amended` block (i) records why: S-B's total carries a
//              PRE-node term that REF3 supplies by NORMALISATION (`pot = 1`, `c0 = c1 = 0.5`), and
//              the four frozen arguments do not carry hero's share of `potSize`, so the interface
//              returns the POST-node half instead. The conversion is exact, one line, and is done
//              in `payoff-fit.mjs` rather than here, because doing it here would silently edit a
//              measurement: `post = invShare - 0.5 / potMult`.
//   eqAB       the MEASURED pairwise checkdown equity for the pair, 20,000 trials. This is form P,
//              the base S-B's own form 1 was fitted on top of. It is a 7,626-entry precompute the
//              Grade-C descope does not build (§3.2), and `payoff-fit.mjs` measures exactly what
//              its absence costs — which is the single largest term in this lane's error.
//   test       1 if the pair is one of the 16 HELD OUT, 0 if it is one of the 34 fitted on. The
//              split is S-B's, made before its own fit, and it is not re-drawn here.
//
// TWO PROPERTIES OF THE MEASUREMENT, recorded because the fit leans on them.
//
// 1. THE REFERENCE DOES NOT CONSERVE EXACTLY ACROSS ITS TWO SEAT RUNS. `ev` is a ratio of
//    expectations, and IP and OOP are separate simulations with slightly different E[F], so
//    `ev(A,A,ip) + ev(A,A,oop)` is 1 only to within run noise: over the 9 self-pair (cell, spr)
//    points here the defect is mean 0.85 pt, max 2.16 pt. Per HAND, inside one run, conservation is
//    exact — S-B verified max |w + w' - F| = 0 over 200,000 random states. So conservation is a
//    property of the game and the 0.85 pt is the reference's own noise; `payoff-model.mjs`
//    therefore enforces it as an identity and eats the disagreement, rather than fitting to it.
// 2. THE INVESTMENT SPLIT CONSERVES MUCH BETTER than `ev` does: over the same 9 points the defect
//    in `q(A,A,ip) + q(A,A,oop) - 1` — q being hero's share of the POST-node money — is mean 0.003.
//    That is why the model parameterises `invShare` through `q` and not directly.
//
// PROVENANCE. Transcribed by the P2 payoff-model lane from `sb-results.json`'s `points` array with
// no arithmetic applied: the numbers below are the spike's own, to the digits it wrote. `REF_META`
// and `SB_PUBLISHED` are likewise verbatim, and `SB_PUBLISHED` exists so the fit here can be
// compared against the fit S-B graded — the row this lane must not quietly beat.

